#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UPSTREAM="${UPSTREAM_DIR:-$ROOT/upstream}"
APP_ROOT="$UPSTREAM/Telegram/Telegram-iOS"
CONFIG="${RUNNER_TEMP:-/tmp}/swiftgram-build-config.json"
BUILD_ARTIFACTS="${RUNNER_TEMP:-/tmp}/swiftgram-build-artifacts"
OUTPUT="$ROOT/artifacts"
APP_DISPLAY_NAME="${APP_DISPLAY_NAME:-Swiftgram}"
BUILD_NUMBER="${BUILD_NUMBER:-0}"
: "${APP_BUNDLE_ID:?Missing APP_BUNDLE_ID}"
[[ -d "$UPSTREAM/.git" && -f "$UPSTREAM/.gitmodules" ]] || { echo 'Expected recursive Swiftgram checkout' >&2; exit 1; }
CANONICAL="/Users/Shared/swiftgram-ios"
sudo rm -rf "$CANONICAL"
sudo mkdir -p "$(dirname "$CANONICAL")"
sudo ditto "$UPSTREAM" "$CANONICAL"
sudo chown -R "$(id -un)" "$CANONICAL"
UPSTREAM="$CANONICAL"
APP_ROOT="$UPSTREAM/Telegram/Telegram-iOS"
python3 "$ROOT/scripts/apply_resign_compat.py" --upstream "$UPSTREAM"
mkdir -p "$OUTPUT"
python3 "$ROOT/scripts/generate_build_config_swiftgram.py" --template "$UPSTREAM/build-system/template_minimal_development_configuration.json" --output "$CONFIG" --notice "$OUTPUT/credentials-notice.txt"
python3 "$ROOT/scripts/enable_unsigned_device_build.py" --make-script "$UPSTREAM/build-system/Make/Make.py" --rules-apple-root "$UPSTREAM/build-system/bazel-rules/rules_apple"
rm -rf "$BUILD_ARTIFACTS"; mkdir -p "$BUILD_ARTIFACTS"
cd "$UPSTREAM"
python3 -u build-system/Make/Make.py --cacheDir="${HOME}/swiftgram-bazel-cache" build --configurationPath="$CONFIG" --xcodeManagedCodesigning --disableProvisioningProfiles --configuration=release_arm64 --buildNumber="$BUILD_NUMBER" --outputBuildArtifactsPath="$BUILD_ARTIFACTS"
python3 "$ROOT/scripts/package_unsigned_ipa.py" --input-ipa "$BUILD_ARTIFACTS/Swiftgram.ipa" --output-ipa "$OUTPUT/Swiftgram-unsigned.ipa" --base-bundle-id "$APP_BUNDLE_ID" --bundle-id "$APP_BUNDLE_ID" --display-name "$APP_DISPLAY_NAME" --contents-report "$OUTPUT/ipa-contents.json"
python3 "$ROOT/scripts/validate_unsigned_ipa.py" --ipa "$OUTPUT/Swiftgram-unsigned.ipa" --bundle-id "$APP_BUNDLE_ID" --report "$OUTPUT/unsigned-ipa-validation.json"
python3 "$ROOT/scripts/write_install_report.py" --contents "$OUTPUT/ipa-contents.json" --validation "$OUTPUT/unsigned-ipa-validation.json" --notice "$OUTPUT/credentials-notice.txt" --stage baseline --output "$OUTPUT/INSTALL.md"
